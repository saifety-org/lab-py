// Command gen-confusables builds confusables_table.go from the Unicode confusables.txt
// (https://www.unicode.org/Public/security/latest/confusables.txt). Only
// entries whose target is plain ASCII letters or digits are kept: that is
// the subset attackers use to hide Latin instructions from pattern matching.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	in := flag.String("in", "datasets/unicode/confusables.txt", "confusables.txt path")
	out := flag.String("out", "artifacts/confusables_table.go", "output Go file")
	flag.Parse()

	f, err := os.Open(*in)
	if err != nil {
		panic(err)
	}
	defer func() { _ = f.Close() }() // Best-effort cleanup.

	table := map[rune]string{}
	var version string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "# Version:") {
			version = strings.TrimSpace(strings.TrimPrefix(line, "# Version:"))
		}
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		parts := strings.Split(line, ";")
		if len(parts) < 2 {
			continue
		}
		src := strings.Fields(parts[0])
		dst := strings.Fields(parts[1])
		if len(src) != 1 || len(dst) == 0 || len(dst) > 3 {
			continue
		}
		s, err := strconv.ParseUint(src[0], 16, 32)
		if err != nil || s < 0x80 {
			continue
		}
		var target strings.Builder
		ok := true
		for _, d := range dst {
			v, err := strconv.ParseUint(d, 16, 32)
			if err != nil || !isASCIIAlnum(rune(v)) {
				ok = false
				break
			}
			target.WriteRune(rune(v))
		}
		if ok {
			table[rune(s)] = target.String()
		}
	}

	if err := sc.Err(); err != nil {
		panic(err)
	}

	keys := make([]rune, 0, len(table))
	for k := range table {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen from Unicode confusables.txt version %s. DO NOT EDIT.\n\n", version)
	b.WriteString("package normalize\n\n")
	b.WriteString("// confusables maps non-ASCII code points to the ASCII letters or digits\n// they are visually confusable with (Unicode TR39, ASCII-target subset).\n")
	b.WriteString("var confusables = map[rune]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t0x%04x: %q,\n", k, table[k])
	}
	b.WriteString("}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "%d entries, version %s\n", len(table), version)
}

func isASCIIAlnum(r rune) bool {
	return r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z'
}
